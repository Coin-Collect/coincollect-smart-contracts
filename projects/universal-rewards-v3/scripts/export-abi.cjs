const fs = require('node:fs')
const { compile } = require('./compile.cjs')

const destination = process.argv[2]
if (!destination) throw new Error('Usage: node scripts/export-abi.cjs <frontend abi.ts>')
const contracts = compile()
const abiExports = [
  ['universalRewardsAbi', 'UniversalRewards'],
  ['rewardSwapAbi', 'RewardSwapAdapter'],
  ['ownershipVerifierAbi', 'FinalizedOwnershipVerifier'],
]
const lines = ['// Generated by projects/universal-rewards-v3/scripts/export-abi.cjs.']
for (const [name, contract] of abiExports) {
  const { abi } = contracts['contracts/' + contract + '.sol'][contract]
  const compact = abi.filter((item) => item.type !== 'constructor').map((item) => '  ' + JSON.stringify(item) + ',')
  lines.push('export const ' + name + ' = [\n' + compact.join('\n') + '\n] as const')
}
fs.writeFileSync(destination, lines.join('\n\n') + '\n')

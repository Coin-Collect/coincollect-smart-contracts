const fs = require('node:fs')
const { compileV36 } = require('./compile-v36.cjs')

const destination = process.argv[2]
if (!destination) throw new Error('Usage: node scripts/export-v36-abi.cjs <frontend abiV36.ts>')
const contracts = compileV36()
const exportsByName = {
  treasuryAssetsV36Abi: 'TreasuryAssetsV36',
  treasuryVaultV36Abi: 'TreasuryVaultV36',
  rewardRoutePlannerV36Abi: 'RewardRoutePlannerV36',
  universalRewardsV36Abi: 'UniversalRewardsV36',
}
const lines = ['// Generated by projects/universal-rewards-v3/scripts/export-v36-abi.cjs.']
for (const [name, contract] of Object.entries(exportsByName)) {
  const { abi } = contracts['contracts/v36/' + contract + '.sol'][contract]
  const compact = abi.filter((item) => item.type !== 'constructor').map((item) => '  ' + JSON.stringify(item) + ',')
  lines.push('// prettier-ignore\nexport const ' + name + ' = [\n' + compact.join('\n') + '\n] as const')
}
fs.writeFileSync(destination, lines.join('\n\n') + '\n')
